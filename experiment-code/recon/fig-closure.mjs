#!/usr/bin/env node
// FIGURE: what the record closed, and where disagreement survives.
//
// Emits a standalone TikZ figure (fig-closure.tex) for the paper's Ring section.
//
// A 3x10 grid: rows are witnesses, columns are the domain's ten coordinates ORDERED BY WHEN
// THE RECORD CLOSED THEM, with the ones it never closes last. The ordering is the whole
// design. Sorted any other way this is a lookup table; sorted by closure time it is a single
// picture of the section's claim — the record owns the left block, the witnesses own only the
// right one, and every disagreement is in the right one.
//
// Colours match fig-filtration.mjs so a reader carries witness identity between the two
// figures. They are used as light tints behind dark text: identity is already carried by the
// row label, so the fill only has to reinforce it, and tinting keeps text contrast high.
//
// Numbers are RECOMPUTED from ring-magistrate-core.mjs on every run, never transcribed.
//
// Usage: node recon/fig-closure.mjs && pdflatex fig-closure.tex

import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
import { buildSpace, poolFor, solve, pinning, jointAudit, satisfies, CAST, COORDS } from './ring-magistrate-core.mjs'
import { LADDER } from './ring-evidence.mjs'

const HERE = path.dirname(url.fileURLToPath(import.meta.url))

const space = buildSpace()

// ---- when did the record close each coordinate? ----
const closedAt = {}
for (let t = 0; t <= LADDER.length; t++) {
  const pin = pinning(poolFor(space, LADDER.slice(0, t)))
  for (const c of COORDS) if (pin[c].pinned && closedAt[c] === undefined) {
    closedAt[c] = { t, doc: t === 0 ? '—' : LADDER[t - 1], val: pin[c].values[0] }
  }
}

const pool = poolFor(space, LADDER)
const sol = solve(pool)
const audit = jointAudit(pool, sol)

// columns: closed first (in closure order), then the ones the record never settles
const ORDER = COORDS.slice().sort((a, b) => (closedAt[a]?.t ?? 99) - (closedAt[b]?.t ?? 99) || (a < b ? -1 : 1))
const nClosed = ORDER.filter(c => closedAt[c]).length

// ---- display forms: short enough for a 1.15cm cell, disambiguated by the column header ----
const SHORT = { true: 'yes', false: 'no', Pompilia: 'Pompilia', Caponsacchi: 'Cap.', Guido: 'Guido', revenge: 'revenge', honor: 'honour', none: 'none' }
const show = (v) => v === null || v === undefined ? '\\textcolor{gray!75}{---}' : (SHORT[String(v)] ?? String(v))

const SERIES = { Guido: '2a78d6', Pompilia: 'eb6834', Caponsacchi: '1baf7a' }

const CW = 1.18, RH = 0.62, LX = 2.05   // cell width, row height, left gutter (cm)
const BAND = 1.62                        // clearance above the grid for the rotated headers
const x = (j) => LX + j * CW + CW / 2
const y = (i) => -i * RH

let cells = ''
CAST.forEach((T, i) => {
  ORDER.forEach((c, j) => {
    const open = !closedAt[c]
    const v = sol[T].commits[c]
    const fill = open ? (v === null ? 'white' : `${T}col!20`) : 'black!7'
    const edge = open && v === null ? 'gray!35' : 'white'
    cells += `  \\node[draw=${edge}, line width=0.5pt, fill=${fill}, minimum width=${CW}cm, minimum height=${RH}cm,` +
             ` inner sep=0pt, font=\\scriptsize] at (${x(j)},${y(i)}) {${show(v)}};\n`
  })
})

// One rotated node per column carrying both lines — the coordinate, and beneath it the
// document that closed it. Two separate nodes at the same angle overlap illegibly.
const headers = ORDER.map((c, j) =>
  `  \\node[anchor=west, rotate=40, align=left, inner sep=1pt, font=\\scriptsize] at (${x(j) - 0.24},${RH * 0.60})` +
  ` {\\ttfamily ${c}\\\\[-2pt]{\\tiny\\itshape\\color{black!58}${closedAt[c] ? closedAt[c].doc : ''}}};`
).join('\n')

const rowLabels = CAST.map((T, i) =>
  `  \\node[anchor=east, font=\\small] at (${LX - 0.12},${y(i)}) {${T}};\n` +
  `  \\node[fill=${T}col, circle, inner sep=1.7pt] at (${LX - 0.05},${y(i)}) {};`
).join('\n')

const gridW = ORDER.length * CW
const divX = LX + nClosed * CW
const topY = RH * 0.5, botY = y(CAST.length - 1) - RH * 0.5

const tex = `% Generated by recon/fig-closure.mjs — do not edit by hand.
\\documentclass[tikz,border=3pt]{standalone}
\\usepackage{amsmath}
${CAST.map(T => `\\definecolor{${T}col}{HTML}{${SERIES[T]}}`).join('\n')}
\\begin{document}
\\begin{tikzpicture}[font=\\small]

  %% band: who owns which block
  \\draw[gray!45, line width=0.5pt] (${LX},${topY + BAND}) -- (${divX - 0.06},${topY + BAND});
  \\draw[gray!45, line width=0.5pt] (${divX + 0.06},${topY + BAND}) -- (${LX + gridW},${topY + BAND});
  %% anchored to the outer edges, not centred on each block: centring lets the two labels
  %% collide at the divider, which is the one place the figure must stay legible.
  \\node[anchor=south west, font=\\scriptsize, text=black!62] at (${LX},${topY + BAND + 0.06})
    {closed by the record (${nClosed}/${COORDS.length}) --- all three concede};
  \\node[anchor=south east, font=\\scriptsize, text=black!62] at (${LX + gridW},${topY + BAND + 0.06})
    {left open (${COORDS.length - nClosed}) --- all disagreement is here};

${headers}

${rowLabels}

${cells}
  %% the one line that matters: the boundary between what the record settles and what it does not
  \\draw[black!70, line width=1.1pt] (${divX},${topY}) -- (${divX},${botY});
  \\draw[gray!30, line width=0.5pt] (${LX},${topY}) -- (${LX + gridW},${topY});
  \\draw[gray!30, line width=0.5pt] (${LX},${botY}) -- (${LX + gridW},${botY});

  \\node[anchor=north west, font=\\scriptsize, text=black!70, align=left] at (${LX - 0.05},${botY - 0.22})
    {Feasible accounts satisfying each witness's assertions: ${CAST.map(T => `${T} ${pool.filter(r => satisfies(r, sol[T])).length}`).join(' $\\cdot$ ')} (of ${pool.length}).\\\\
     No account satisfies any \\emph{two} of them: all three pairwise intersections are empty.};

\\end{tikzpicture}
\\end{document}
`

fs.writeFileSync(path.join(HERE, 'fig-closure.tex'), tex)

console.log('\nwrote fig-closure.tex\n')
console.log(`  ${'coordinate'.padEnd(13)}${'closed by'.padEnd(15)}${CAST.map(T => T.padEnd(13)).join('')}`)
for (const c of ORDER) {
  console.log(`  ${c.padEnd(13)}${(closedAt[c] ? closedAt[c].doc : '— OPEN —').padEnd(15)}` +
    CAST.map(T => String(sol[T].commits[c] ?? '—').padEnd(13)).join(''))
}
console.log(`\n  closed ${nClosed}/${COORDS.length}; all three concede every closed coordinate.`)
console.log(`  satisfying regions: ${CAST.map(T => `${T}=${pool.filter(r => satisfies(r, sol[T])).length}`).join(', ')} of ${pool.length}`)
console.log(`  pairs: ${JSON.stringify(audit.pairs)}  all three: ${audit.jointly}\n`)
