#!/usr/bin/env node
// FIGURE: the filtration, and what it costs each witness.
//
// Emits a standalone pgfplots figure (fig-filtration.tex) for the paper's Ring section.
//
// The numbers are RECOMPUTED from ring-magistrate-core.mjs on every run rather than
// transcribed. A figure with hand-copied numbers is a figure that silently goes stale the
// first time the domain changes; this one cannot, and `node recon/test-ring.mjs` already
// guards the modules it reads.
//
// Two panels, one shared x-axis. Deliberately NOT a dual-axis plot: |Feas| and U have
// nothing to do with each other dimensionally, and overlaying them on twin y-scales is the
// single most common way to make a chart lie. They are stacked instead, with the turning
// points drawn as rules crossing BOTH panels, so the coupling that matters — this document
// removed these accounts AND cost this witness that much — is read off vertically.
//
// Usage: node recon/fig-filtration.mjs && pdflatex fig-filtration.tex

import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
import { buildSpace, poolFor, solve, CAST } from './ring-magistrate-core.mjs'
import { LADDER, FACTS } from './ring-evidence.mjs'

const HERE = path.dirname(url.fileURLToPath(import.meta.url))
const u100 = (x) => Math.round(100 * x)

// ---- recompute the trajectory ----
const space = buildSpace()
const steps = []
let prev = null
for (let t = 0; t <= LADDER.length; t++) {
  const pool = poolFor(space, LADDER.slice(0, t))
  const sol = solve(pool)
  const caught = prev
    ? CAST.filter(T => !prev.sol[T].maxers.some(r => pool.some(p => p.assertion === r.assertion)))
    : []
  steps.push({
    t, doc: t === 0 ? '(opening)' : LADDER[t - 1],
    n: pool.length,
    u: Object.fromEntries(CAST.map(T => [T, u100(sol[T].u)])),
    caught,
  })
  prev = { pool, sol }
}

// ---- categorical palette: slots 1-3, validated all-pairs in light mode ----
// (scripts/validate_palette.js "#2a78d6,#eb6834,#1baf7a" --mode light --pairs all)
// The aqua slot sits below 3:1 on a light surface, so the relief rule applies and every
// series carries a visible direct label. Markers differ per series as well, so identity
// survives greyscale printing.
const SERIES = {
  Guido:       { color: '2a78d6', mark: '*',          label: 'Guido' },
  Pompilia:    { color: 'eb6834', mark: 'square*',    label: 'Pompilia' },
  Caponsacchi: { color: '1baf7a', mark: 'triangle*',  label: 'Caponsacchi' },
}

const coords = (f) => steps.map(s => `(${s.t},${f(s)})`).join(' ')
const turning = steps.filter(s => s.caught.length)

// rules crossing both panels, at the documents that broke somebody's standing account
const rules = (yLo, yHi, logY) => turning.map(s =>
  `    \\draw[gray!45, dashed, line width=0.4pt] (axis cs:${s.t},${yLo}) -- (axis cs:${s.t},${yHi});`
).join('\n')

// A witness is "caught out" when the arriving document removed every account attaining their
// previous maximum. Drawn as a white-cored ring so it reads as an event on the curve rather
// than as one more sample marker.
const caughtMarks = CAST.map(T => {
  const pts = steps.filter(s => s.caught.includes(T))
  if (!pts.length) return ''
  return `    \\addplot[only marks, mark=*, mark size=4.2pt, draw=${T}col, fill=white,` +
         ` line width=1.1pt, forget plot]\n` +
         `      coordinates {${pts.map(s => `(${s.t},${s.u[T]})`).join(' ')}};`
}).filter(Boolean).join('\n')

const tex = `% Generated by recon/fig-filtration.mjs — do not edit by hand.
% Regenerate after any change to ring-domain / ring-objective / ring-evidence.
\\documentclass[tikz,border=3pt]{standalone}
\\usepackage{pgfplots}
\\pgfplotsset{compat=1.18}
\\usepgfplotslibrary{groupplots}
\\usepackage{amsmath}

${CAST.map(T => `\\definecolor{${T}col}{HTML}{${SERIES[T].color}}`).join('\n')}
\\definecolor{feascol}{HTML}{52514E}
\\definecolor{inkcol}{HTML}{0B0B0B}

\\begin{document}
\\begin{tikzpicture}[font=\\small]
\\begin{groupplot}[
    group style={group size=1 by 2, vertical sep=3.5mm, x descriptions at=edge bottom},
    width=14.2cm,
    xmin=-0.45, xmax=11.45,
    xtick={${steps.map(s => s.t).join(',')}},
    xticklabels={${steps.map(s => s.t === 0 ? '\\textit{opening}' : `\\texttt{${s.doc}}`).join(', ')}},
    x tick label style={rotate=42, anchor=east, font=\\scriptsize},
    tick align=outside, tick pos=left,
    axis line style={gray!55, line width=0.4pt},
    grid=major, grid style={gray!18, line width=0.3pt},
    every axis plot/.append style={line width=1.3pt},
    label style={font=\\small}, tick label style={font=\\scriptsize},
  ]

  %% ---- top panel: the filtration itself ----
  \\nextgroupplot[
    height=3.6cm, ymode=log, ymin=26, ymax=1150, clip=false,
    ytick={36,72,144,288,576}, yticklabels={36,72,144,288,576},
    log ticks with fixed point,
    ylabel={$|\\mathrm{Feas}(F_t)|$},
    ylabel style={align=center},
  ]
${rules(26, 1150, true)}
    \\addplot[const plot, mark=none, color=feascol] coordinates {${coords(s => s.n)}};
    \\node[anchor=west, font=\\scriptsize, text=feascol] at (axis cs:0.15,880) {576 assertions};
    \\node[anchor=west, font=\\scriptsize, text=feascol] at (axis cs:11.6,36) {36 survive};
    \\node[anchor=west, font=\\scriptsize\\itshape, text=gray!75] at (axis cs:11.6,80) {$16\\times$};

  %% ---- bottom panel: what it cost each witness ----
  \\nextgroupplot[
    height=4.8cm, ymin=12, ymax=118, clip=false,
    ytick={25,50,75,100},
    ylabel={$U_i(\\hat\\tau_i)$},
    xlabel={documents of the Old Yellow Book, in the order the magistrate files them},
    xlabel style={font=\\scriptsize, yshift=-1mm},
    legend style={at={(0.03,0.05)}, anchor=south west, draw=gray!40, fill=white,
                  font=\\scriptsize, row sep=-1pt, /tikz/every even column/.append style={column sep=5pt}},
    legend columns=3,
  ]
${rules(12, 118, false)}
${CAST.map(T => `    \\addplot[const plot, mark=${SERIES[T].mark}, mark size=1.9pt, color=${T}col] coordinates {${coords(s => s.u[T])}};\n    \\addlegendentry{${SERIES[T].label}}`).join('\n')}
${caughtMarks}
${CAST.map(T => {
  const last = steps[steps.length - 1], first = steps[0]
  const d = last.u[T] - first.u[T]
  // math mode so the sign is a real minus, not a hyphen
  const delta = d === 0 ? '$\\pm0$' : `$${d < 0 ? '-' : '+'}${Math.abs(d)}$`
  // Identity is carried by the line arriving at this height and by the legend; the text
  // itself stays in ink rather than series colour.
  return `    \\node[anchor=west, font=\\scriptsize, text=inkcol] at (axis cs:11.6,${last.u[T]})` +
         ` {${SERIES[T].label}\\ \\textbf{${last.u[T]}}\\ \\textcolor{gray}{\\textit{${delta}}}};`
}).join('\n')}
    \\node[anchor=west, font=\\scriptsize\\itshape, text=gray!70] at (axis cs:-0.3,112) {all three at their unconstrained ideal, $U_i=100$};

\\end{groupplot}
\\end{tikzpicture}
\\end{document}
`

fs.writeFileSync(path.join(HERE, 'fig-filtration.tex'), tex)

// ---- report, so the caption can be written against the same numbers ----
console.log('\nwrote fig-filtration.tex\n')
console.log(`  ${'t'.padEnd(3)}${'document'.padEnd(15)}${'|Feas|'.padEnd(8)}${CAST.map(T => T.padEnd(13)).join('')}caught`)
for (const s of steps) {
  console.log(`  ${String(s.t).padEnd(3)}${s.doc.padEnd(15)}${String(s.n).padEnd(8)}` +
    CAST.map(T => String(s.u[T]).padEnd(13)).join('') + (s.caught.join(', ') || ''))
}
const f = steps[0], l = steps[steps.length - 1]
console.log(`\n  contraction: ${f.n} -> ${l.n} assertions (${(f.n / l.n).toFixed(1)}x)`)
for (const T of CAST) console.log(`  ${T.padEnd(13)} ${f.u[T]} -> ${l.u[T]}  (${l.u[T] - f.u[T] >= 0 ? '+' : ''}${l.u[T] - f.u[T]})`)
console.log(`  turning points: ${turning.map(s => `${s.doc} (${s.caught.join('+')})`).join(', ')}\n`)
