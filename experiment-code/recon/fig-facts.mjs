#!/usr/bin/env node
// FIGURE: what the public record F actually says, in each of the three domains.
//
// Companion panel to fig-domains: that table shows what F DOES (a large space collapsing to a
// small feasible set); this one shows what F IS — the literal items an investigator could
// establish, domain by domain. Intended as subfigure (a) of the same figure, with the bar
// count table as (b).
//
// Every line is DERIVED from the same objects feasibility is decided against — grove's
// AFTERMATH spec, ring's LADDER/FACTS, ops's RECORD — through a phrasing layer that THROWS
// on any key it does not know. If a domain gains or loses a fact, this figure refuses to
// build rather than going quietly stale. The |Feas(F)| counts in each card are asserted
// against the enumerations (11 / 36 / 48), and the colour of those numbers is the same
// green as fig-domains' feasible bars, so the two panels read as one system.
//
// NO LLM. Usage: node recon/fig-facts.mjs && pdflatex fig-facts.tex

import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'

const HERE = path.dirname(url.fileURLToPath(import.meta.url))
const esc = (s) => s.replace(/&/g, '\\&').replace(/%/g, '\\%').replace(/#/g, '\\#')

// ---- grove: the run-06 aftermath spec, phrased per key, unknown keys refused ----
const D = await import('./domain.mjs')
const G = D.AFTERMATH["pre-B'/run-06"]
const groveLines = []
for (const [k, v] of Object.entries(G)) {
  if (k === 'dead') for (const d of v) groveLines.push(`${d.who} dead from a ${d.weapon} wound to the ${d.part}`)
  else if (k === 'alivePresent') for (const w of v) groveLines.push(`${w} was alive at the scene`)
  else if (k === 'gone') for (const w of v) groveLines.push(`${w} was gone`)
  else if (k === 'bloodied') for (const w of v) groveLines.push(`the ${w} was bloodied`)
  else if (k === 'notBloodied') for (const w of v) groveLines.push(`the ${w} was clean`)
  else if (k === 'rope') groveLines.push(`the rope was ${v}`)
  else throw new Error(`grove F has a key this figure does not know: ${k}`)
}

// ---- ring: the eleven documents, in filing order, phrased per id ----
const E = await import('./ring-evidence.mjs')
const RING_PHRASE = {
  flight: 'the pair left Arezzo by night',
  castelnuovo: 'taken at the inn, short of Rome',
  lettersFiled: 'letters produced at the flight-trial',
  suit: 'Guido had brought suit',
  sentence: "the priest received three years' relegation",
  convent: 'she placed in a convent, then out',
  birth: 'a son born, 18 December 1697',
  hiredMen: 'four hired men at the villa',
  theName: "the door was gained by ``Caponsacchi''",
  fourDays: 'she lived four days and gave evidence',
  gate: 'Guido stopped at the gate, no pass',
}
for (const id of E.LADDER) if (!(id in RING_PHRASE)) throw new Error(`ring document not phrased: ${id}`)
for (const id of Object.keys(RING_PHRASE)) if (!E.LADDER.includes(id)) throw new Error(`stale ring phrase: ${id}`)
const ringLines = E.LADDER.map(id => RING_PHRASE[id])

// ---- ops: the RECORD object, phrased per key (with the incident descriptor first) ----
const S = await import('./ops-domain.mjs')
const opsLines = ['a destructive write dropped a live table']
for (const [k, v] of Object.entries(S.RECORD)) {
  if (k === 'actor') opsLines.push(`the call came from the ${String(v).toLowerCase()}'s process`)
  else throw new Error(`ops RECORD has a key/value this figure does not know: ${k}=${v}`)
}

// ---- the feasible counts each record leaves, asserted against the enumerations ----
const GC = await import('./game-core.mjs')
const RH = await import('./ring-hearing.mjs')
const OE = await import('./ops-enum.mjs')
const feas = { grove: GC.feasibles.length, ring: RH.fullPool(RH.buildSpace()).length, ops: OE.feasibles.length }
const expect = { grove: 11, ring: 36, ops: 48 }
for (const k of Object.keys(expect)) if (feas[k] !== expect[k])
  throw new Error(`|Feas| changed for ${k}: ${feas[k]} (figure and paper say ${expect[k]})`)

// ---- emit: three cards, one per record ----
const card = (x, title, sub, lines, n) => `
\\begin{scope}[shift={(${x},0)}]
  \\node[card] (c) {\\begin{minipage}{4.05cm}\\raggedright
    ${lines.map(l => `{\\hangindent=0.95em\\hangafter=1 \\itemdot ${esc(l)}\\par}\\vspace{0.14em}`).join('\n    ')}
    \\vspace{0.18em}\\hrule height 0.4pt \\vspace{0.28em}
    {\\scriptsize leaves \\textcolor{cFeas}{$|\\mathrm{Feas}(F)|=${n}$}}
  \\end{minipage}};
  \\node[hdr, anchor=south west] at (c.north west) {\\textbf{${title}}\\enspace{\\scriptsize ${sub}}};
\\end{scope}`

const tex = `% Generated by recon/fig-facts.mjs — the public record F, domain by domain.
% Derived from AFTERMATH / LADDER+FACTS / RECORD; the script throws if any of them changes.
\\documentclass[tikz,border=3pt]{standalone}
\\usepackage{times}
\\definecolor{cFeas}{HTML}{4C9A4C}
\\newcommand{\\itemdot}{\\textcolor{black!60}{\\raisebox{0.12em}{\\tiny$\\bullet$}}\\hspace{0.35em}}
\\begin{document}
\\begin{tikzpicture}[
  card/.style={draw=black!45, line width=0.4pt, fill=black!3, inner sep=6pt, anchor=north west},
  hdr/.style={inner sep=2pt, font=\\footnotesize},
  font=\\scriptsize,
]
${card(0, 'In a Grove', 'six public facts', groveLines, feas.grove)}
${card(4.85, 'The Ring', 'eleven filed facts', ringLines, feas.ring)}
${card(9.7, 'Ops incident', 'two public facts', opsLines, feas.ops)}
\\end{tikzpicture}
\\end{document}
`
fs.writeFileSync(path.join(HERE, 'fig-facts.tex'), tex)
console.log('facts per domain:', groveLines.length, '/', ringLines.length, '/', opsLines.length)
console.log('|Feas| asserted:', JSON.stringify(feas))
console.log('written: recon/fig-facts.tex')
