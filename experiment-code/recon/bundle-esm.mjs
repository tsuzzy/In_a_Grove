// The ESM→classic-script transform, lifted out of build-magistrate.mjs so the Franceschini
// bundle can use it too.
//
// It is a real (tiny) module system rather than a concatenation, because concatenating would
// collide: the grove's domain.mjs and hearing-core.mjs both define CAST, ring-objective.mjs
// defines its own CAST and label, and half the modules define argmaxBy. Each module keeps its
// own scope and asks for its dependencies through __req, exactly as ESM would.
//
// The point is that a page runs the SAME code as the node scripts. There is one solver per
// domain and the bundle is generated from it, rather than being a second implementation —
// the failure mode this project keeps hitting.

import { readFileSync, writeFileSync } from 'node:fs'

/** rewrite one ESM source into a function body that fills `exports` */
export function transform(src, name) {
  let s = src

  // `import { a, b } from './x.mjs'`  ->  const { a, b } = __req('./x.mjs')
  s = s.replace(/^import\s*\{([^}]*)\}\s*from\s*'(\.\/[^']+)'\s*$/gm,
    (_, names, from) => `const {${names}} = __req('${from}')`)

  // `export { a, b } from './x.mjs'`  ->  pull in and re-publish
  s = s.replace(/^export\s*\{([^}]*)\}\s*from\s*'(\.\/[^']+)'\s*$/gm, (_, names, from) => {
    const list = names.split(',').map(n => n.trim()).filter(Boolean)
    return `const {${names}} = __req('${from}')\n` + list.map(n => `exports.${n} = ${n}`).join('\n')
  })

  const named = []
  s = s.replace(/^export\s+(const|let|var)\s+([A-Za-z0-9_$]+)/gm, (_, kind, id) => { named.push(id); return `${kind} ${id}` })
  s = s.replace(/^export\s+function\s+([A-Za-z0-9_$]+)/gm, (_, id) => { named.push(id); return `function ${id}` })
  s = s.replace(/^export\s+function\*\s+([A-Za-z0-9_$]+)/gm, (_, id) => { named.push(id); return `function* ${id}` })

  // bare `export { a, b }`
  s = s.replace(/^export\s*\{([^}]*)\}\s*$/gm, (_, names) => {
    for (const n of names.split(',').map(x => x.trim()).filter(Boolean)) named.push(n)
    return ''
  })

  if (/^\s*(import|export)\s/m.test(s)) {
    const leftover = s.split('\n').filter(l => /^\s*(import|export)\s/.test(l))
    throw new Error(`${name}: unhandled module syntax:\n  ${leftover.join('\n  ')}`)
  }

  const publish = [...new Set(named)].map(n => `  exports.${n} = ${n}`).join('\n')
  return `__defs['${name}'] = function () {\n  const exports = {}\n${s}\n${publish}\n  return exports\n}`
}

/** emit one classic script exposing `global[globalName] = { alias: module, … }` */
export function bundle({ modules, expose, globalName, outFile, generator }) {
  const parts = modules.map(m => transform(readFileSync(m.path, 'utf8'), m.name))
  const out = `// GENERATED by ${generator} — do not edit.
// The browser runs the same solver as the node scripts; this file is emitted from it.
;(function (global) {
'use strict'
const __defs = {}, __mods = {}
function __req(name) {
  if (!(name in __mods)) __mods[name] = __defs[name]()
  return __mods[name]
}
${parts.join('\n\n')}

global.${globalName} = {
${Object.entries(expose).map(([k, v]) => `  ${k}: __req('${v}'),`).join('\n')}
}
})(typeof globalThis !== 'undefined' ? globalThis : this)
`
  writeFileSync(outFile, out)
  return out.length
}
